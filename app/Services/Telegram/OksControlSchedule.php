<?php

namespace App\Services\Telegram;

use App\Models\TelegramScheduledMessageDelivery;

class OksControlSchedule
{
    public const SPLIT_FIRST_FINISH = 'oks_split_first_finish';

    public const COPY_VERSION = 'oks_copy_version';

    public const CURRENT_COPY_VERSION = 2;

    // Historic deliveries keep their original questions; new checks use the copy from the comparison.
    public const COPY_V2_START_DATE = '2026-11-23';

    public const TIMES = [
        '09:30' => 'oks_schedule',
        '10:15' => 'oks_start_ten',
        '11:00' => 'oks_start_eleven',
        '11:05' => 'oks_linen',
        '12:00' => 'oks_first_progress',
        '12:30' => 'oks_first_finish',
        '14:00' => 'oks_guest_arrivals',
        '16:00' => 'oks_couriers',
        '17:30' => 'oks_cleanings',
        '18:00' => 'oks_payments',
    ];

    public const LABELS = [
        'oks_schedule' => 'Время уборок и заметки',
        'oks_start_ten' => 'Начало уборок в 10:00',
        'oks_start_eleven' => 'Уборки до 11:00 и поздние выезды',
        'oks_linen' => 'Проверка доставок постельного белья',
        'oks_first_progress' => 'Первые уборки по графику',
        'oks_first_finish' => 'Повторный контроль первых уборок',
        'oks_guest_arrivals' => 'Готовность квартир к заезду гостей',
        'oks_couriers' => 'Курьерские доставки',
        'oks_cleanings' => 'Завершение всех уборок',
        'oks_payments' => 'Доплаты за день',
    ];

    public static function questionsFor(TelegramScheduledMessageDelivery $delivery): array
    {
        $context = $delivery->sequence_context ?? [];

        return self::questions(
            $delivery->control_type,
            ($context[self::SPLIT_FIRST_FINISH] ?? false) === true,
            (int) ($context[self::COPY_VERSION] ?? 1),
        );
    }

    public static function questions(string $type, bool $splitFirstFinish = false, int $copyVersion = self::CURRENT_COPY_VERSION): array
    {
        $updated = $copyVersion >= self::CURRENT_COPY_VERSION;

        return match ($type) {
            'oks_schedule' => ['check' => self::question('Время уборок и заметки проверены?', 'Проверили', 'Есть расхождения', 'Какой заезд, время или заметку нужно уточнить?',
                $updated
                    ? 'Проверяем, актуальны ли заезды, не появились ли новые и соответствует ли график реальной ситуации. Также сверяем, что заметки PM соответствуют заметкам для клинеров.'
                    : 'Проверяем актуальность заездов, новые заезды и соответствие графика реальной ситуации. Сверяем заметки PM с заметками для клинеров.')],
            'oks_start_ten' => [
                'start' => self::question('Все уборки, запланированные на 10:00, начались?', 'Все начались', 'Не все', 'Какие уборки на 10:00 ещё не начались и почему?'),
                'late' => self::question('Уборки с поздним выездом под контролем?', 'Под контролем', 'Есть риск', 'Какая уборка под риском и что нужно сделать?', skip: 'Поздних выездов нет'),
            ],
            'oks_start_eleven' => $updated ? [
                'start' => self::question('Все уборки, запланированные до 11:00, начались?', '✅ Все начались', '🔴 Не все',
                    'Какие уборки не начались, почему и какие меры нужно принять?',
                    'Определить, какие уборки не начались, выяснить причину задержки и принять меры для соблюдения графика. Добавить EXTRA TIME, если ожидание выезда гостей составило 30 минут или более.'),
            ] : [
                'start' => self::question('Все уборки, запланированные до 11:00, начались?', 'Все начались', 'Не все', 'Какие уборки не начались, почему и что делаем, чтобы сохранить график?'),
                'late' => self::question('Гости с поздним выездом освободили квартиры?', 'Освободили', 'Ещё нет', 'Какие квартиры ещё заняты и что делаем, чтобы сохранить график?',
                    'Если ожидание выезда гостей составило 30 минут или больше, добавляем EXTRA TIME.', skip: 'Поздних выездов нет'),
            ],
            'oks_linen' => ['check' => self::question('Постельное бельё доставлено в приоритетные квартиры?', $updated ? '✅ Доставили' : 'Доставили', $updated ? '🔴 Не везде' : 'Не везде',
                'В какие приоритетные квартиры бельё ещё не доставили и почему?', skip: 'Нет приоритета по белью')],
            'oks_first_progress' => ['check' => self::question('Первые уборки выполняются по графику?', $updated ? '✅ Да, график соблюдается' : 'По графику', $updated ? '🔴 Нет, есть отставание' : 'Есть отставание',
                'Какая уборка отстаёт, почему и есть ли риск для следующих? Если меняем график, напиши как.',
                $updated
                    ? 'Проверяем ход выполнения первых уборок с учётом индивидуального времени начала и запланированной продолжительности. В больших квартирах с продолжительностью уборки от 240 минут к 12:00 клинер должен приступить к этапу влажной уборки поверхностей. ✅ Да — уборки выполняются по графику, необходимые этапы достигнуты, риска задержек нет. 🔴 Нет — выявляем причину отставания, оцениваем риск задержки последующих уборок и при необходимости корректируем график.'
                    : 'Сверяем ход уборок с индивидуальным временем начала и длительностью. В больших квартирах с уборкой от 240 минут к 12:00 клинер должен приступить к влажной уборке поверхностей.')],
            'oks_first_finish' => $splitFirstFinish ? [
                // Historic two-question cards retain both answers and their original keys.
                'check' => self::question('Первые уборки закончатся вовремя?', 'Успевают', 'Есть риск', 'Какие первые уборки рискуют затянуться и почему?'),
                'next' => self::question('Вторые уборки начнутся по графику?', 'По графику', 'Есть риск',
                    'Какие вторые уборки могут начаться позже и что меняем в графике?', skip: 'Вторых уборок нет'),
            ] : ['check' => $updated
                ? self::question('Успевают ли клинеры завершить первые уборки так, чтобы все последующие уборки были выполнены вовремя по индивидуальному графику?',
                    '✅ Да, риска опозданий нет', '🔴 Нет, меняем график', 'Какие уборки под риском и что меняем в графике?')
                : self::question('Успеют ли клинеры завершить первые уборки без сдвига следующих?', 'Успевают', 'Есть риск',
                    'Какие уборки рискуют опоздать и что меняем в графике?', 'Проверяем последующие уборки по индивидуальному графику. Если задержка первых угрожает следующим, меняем график.')],
            'oks_guest_arrivals' => ['check' => self::question($updated
                ? 'Все уборки идут по графику и будут завершены к заезду гостей?'
                : 'Все уборки идут по графику и завершатся к заезду гостей?', 'Рисков нет', 'Заезд под риском',
                'Какая квартира под риском, почему и что передаём PM?', 'Проверяем статус каждой квартиры. Если заезд под риском, принимаем меры и передаём информацию PM.')],
            'oks_couriers' => ['check' => self::question('Курьеры завершили все доставки?', 'Всё доставили', 'Остались доставки', 'Какие доставки ещё не завершили и почему?')],
            'oks_cleanings' => ['check' => self::question('Все уборки завершены?', 'Все завершили', 'Ещё идут', 'Что осталось и почему?')],
            'oks_payments' => ['check' => self::question('Все доплаты за день произведены?', 'Все доплаты внесли', 'Ещё не все', 'Какие доплаты остались и почему?')],
            default => [],
        };
    }

    private static function question(string $title, string $yes, string $no, string $prompt, string $details = '', ?string $skip = null): array
    {
        return compact('title', 'yes', 'no', 'prompt', 'details', 'skip');
    }
}
